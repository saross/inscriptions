# Q1 -- Width distribution
# ---------------------------------------------------------------------------
def q1_width_distribution(df: pd.DataFrame) -> dict:
    """Width percentiles, modal concentration, and a log-scale histogram.

    Returns a dict of results used by the report writer.
    """
    widths = df["width"].to_numpy()
    n = len(widths)

    # Percentiles requested by the brief.
    pctiles = [5, 10, 25, 50, 75, 90, 95]
    pct_values = np.percentile(widths, pctiles)
    pct_df = pd.DataFrame({"percentile": pctiles, "width_years": pct_values})
    pct_df.to_csv(TBL_DIR / "width-percentiles.csv", index=False)

    # Modal-width concentration table. Each "round" width is plausibly tied
    # to a specific dating convention: 100 = inclusive century slab,
    # 50 = half-century, 25 = quarter-century, 10 = decade, 5 = lustrum,
    # 1 = exact year. (Also report 200 as multi-century slab indicator.)
    modal_widths = [1, 5, 10, 25, 50, 100, 200]
    modal_rows = []
    for w in modal_widths:
        count = int((widths == w).sum())
        modal_rows.append({"width_years": w, "count": count, "share": count / n})
    modal_df = pd.DataFrame(modal_rows)
    modal_df.to_csv(TBL_DIR / "modal-width-concentration.csv", index=False)

    # ---- Histogram (log-scale y-axis, integer-width bins up to 500) ----
    fig, ax = plt.subplots(figsize=(10, 5))
    # Bin edges at integer widths 1..500. Beyond 500 widths get aggregated.
    max_plot_width = 500
    plot_widths = widths.copy()
    overflow = (plot_widths > max_plot_width).sum()
    plot_widths = np.clip(plot_widths, 1, max_plot_width)
    bins = np.arange(0.5, max_plot_width + 1.5)
    ax.hist(plot_widths, bins=bins, color="#444477", edgecolor="none")
    ax.set_yscale("log")
    ax.set_xlabel("Interval width (years, inclusive-Roman)")
    ax.set_ylabel("Inscription count (log scale)")
    ax.set_title(
        f"Interval-width distribution -- LIRE v3.0 filtered corpus (n = {n:,}); "
        f"widths > {max_plot_width} clipped (n = {overflow:,})"
    )
    # Annotate the convention-suggestive peaks. Use a small vertical offset that
    # lifts each label clear of the bar tip; place labels right of the bar for
    # the dense low-width region to avoid overlap.
    ax.set_ylim(top=max(1, (widths == 100).sum()) * 12)  # headroom for labels
    for w in modal_widths:
        count = int((widths == w).sum())
        if count == 0:
            continue
        # Tail-anchored placement: small widths label to the right, larger to centre.
        xtext_offset = 6 if w <= 25 else 0
        ax.annotate(
            f"w={w}\n{count:,}",
            xy=(w, count),
            xytext=(w + xtext_offset, count * 4),
            ha="left" if xtext_offset else "center",
            fontsize=8,
            arrowprops=dict(arrowstyle="->", color="black", lw=0.5),
        )
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig1-width-histogram.png", dpi=140)
    plt.close(fig)

    return {
        "n": n,
        "percentiles": dict(zip(pctiles, pct_values.tolist())),
        "modal": modal_df.to_dict(orient="records"),
    }


