# Q4 -- Counterfactual: remove narrow intervals and re-measure O/E at spikes
# ---------------------------------------------------------------------------
def _midpoint_oe_at_spike(df: pd.DataFrame, spike: int) -> tuple[float, float, float, int]:
    """Compute (observed, expected_aoristic, ratio, n) for the integer-midpoint test.

    This replicates the *canonical* test from
    runs/2026-04-23-descriptive-stats/code/profile.py::run_aoristic_mc_test
    with endpoint_label='mid':

      observed = # rows where int((nb+na)/2) == spike
      expected = aoristic null = sum over rows of (1/width) for rows where
                 nb <= spike <= na.

    The ratio observed/expected is exactly the 22.8x / 41.5x / 18.8x statistic.

    n is the row count of the input subset (for reporting).
    """
    nb = df["not_before"].to_numpy()
    na = df["not_after"].to_numpy()
    w = df["width"].to_numpy()
    mid_int = ((nb + na) / 2.0).astype(int)

    observed = float((mid_int == spike).sum())
    # Aoristic expected: each row that spans the year contributes 1/width.
    spans = (nb <= spike) & (spike <= na)
    expected = float((1.0 / w[spans]).sum()) if spans.any() else 0.0
    ratio = observed / expected if expected > 0 else float("nan")
    return observed, expected, float(ratio), int(len(df))


def q4_counterfactual(df: pd.DataFrame) -> pd.DataFrame:
    """O/E at each spike under (a) full corpus and (b) width > 25 subset.

    Uses the canonical integer-truncated-midpoint statistic so the absolute O/E
    ratios are directly comparable to the headline 22.8x / 41.5x / 18.8x reported
    in artefacts.md. Sanity check: the 'full' row should reproduce those ratios
    to ~3 significant figures.

    Mechanism interpretation:
      - Mechanism (b) -- narrow midpoint anchors -- if the wide-only ratio
        collapses dramatically (e.g. from 22.8x to ~2x).
      - Mechanism (a) -- wide century slabs -- if the wide-only ratio stays
        comparably high. Wide slabs [1, 100] / [101, 200] / [201, 300] survive
        the width > 25 filter (their widths are 100), and their midpoints
        truncate to 50 / 150 / 250.
    """
    wide_only = df.loc[df["width"] > 25].copy()
    print(f"  full corpus: n = {len(df):,}")
    print(f"  wide-only (width > 25): n = {len(wide_only):,}")

    rows = []
    for spike in SPIKE_YEARS:
        obs_f, exp_f, r_f, _ = _midpoint_oe_at_spike(df, spike)
        obs_w, exp_w, r_w, _ = _midpoint_oe_at_spike(wide_only, spike)
        rows.append({
            "spike_year": spike,
            "full_n": len(df),
            "full_observed": obs_f,
            "full_expected": exp_f,
            "full_oe": r_f,
            "wide_only_n": len(wide_only),
            "wide_only_observed": obs_w,
            "wide_only_expected": exp_w,
            "wide_only_oe": r_w,
            "oe_retained_fraction": r_w / r_f if r_f > 0 else float("nan"),
        })
    out = pd.DataFrame(rows)
    out.to_csv(TBL_DIR / "counterfactual-oe.csv", index=False)

    # ---- Plot: side-by-side O/E bars at each spike ----
    fig, ax = plt.subplots(figsize=(9, 5.5))
    x = np.arange(len(SPIKE_YEARS))
    bar_w = 0.4
    ax.bar(x - bar_w / 2, out["full_oe"], bar_w, label="Full corpus", color="#1b4f9c")
    ax.bar(x + bar_w / 2, out["wide_only_oe"], bar_w, label="Width > 25 only", color="#c44a1a")
    ax.set_xticks(x)
    ax.set_xticklabels([f"AD {y}" for y in SPIKE_YEARS])
    ax.axhline(1.0, color="black", lw=0.7, linestyle=":")
    ax.set_ylabel("Observed / expected (canonical aoristic null)")
    ax.set_title(
        "Counterfactual: integer-midpoint O/E spike with vs without narrow intervals\n"
        "(width > 25 keeps wide-slab inscriptions; drops candidate midpoint-anchor inscriptions)"
    )
    # Annotate each bar with its O/E ratio.
    for xi, full, wide in zip(x, out["full_oe"], out["wide_only_oe"]):
        ax.text(xi - bar_w / 2, full, f"{full:.1f}x", ha="center", va="bottom", fontsize=9)
        ax.text(xi + bar_w / 2, wide, f"{wide:.1f}x", ha="center", va="bottom", fontsize=9)
    ax.legend()
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig4-counterfactual-oe.png", dpi=140)
    plt.close(fig)

    return out


