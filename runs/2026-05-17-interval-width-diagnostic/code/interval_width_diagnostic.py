# ---------------------------------------------------------------------------
# Analysis envelope -- the 50 BC to AD 350 window used in the preregistration.
# ---------------------------------------------------------------------------
ENVELOPE_MIN = -50
ENVELOPE_MAX = 350

# Spike years to decompose. Bins are inclusive 5-year windows centred on each
# spike (year +/- 2). The descriptive profile reports O/E ratios at these years.
SPIKE_YEARS = [50, 150, 250]
SPIKE_BIN_HALF_WIDTH = 2  # so the bin around year Y is [Y - 2, Y + 2], 5 years wide.

# Width buckets for stratified analyses. Edges are designed to isolate
# 'narrow' (<=25 yr, candidate mechanism b) from 'century-slab' (~100 yr,
# candidate mechanism a) and wider intervals (multi-century coverage).
WIDTH_BUCKETS = [
    ("width = 1", lambda w: w == 1),
    ("1 < width <= 10", lambda w: (w > 1) & (w <= 10)),
    ("10 < width <= 25", lambda w: (w > 10) & (w <= 25)),
    ("25 < width <= 50", lambda w: (w > 25) & (w <= 50)),
    ("50 < width <= 100", lambda w: (w > 50) & (w <= 100)),
    ("100 < width <= 200", lambda w: (w > 100) & (w <= 200)),
    ("width > 200", lambda w: w > 200),
]


