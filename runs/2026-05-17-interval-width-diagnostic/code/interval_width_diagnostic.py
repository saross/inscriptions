# Q2 -- Width x midpoint cross-tabulation
# ---------------------------------------------------------------------------
def q2_midpoint_by_width(df: pd.DataFrame) -> None:
    """Plot midpoint distribution stratified by width bucket.

    Each subplot shows where the midpoints of inscriptions in a given width
    bucket fall within the analysis envelope. We expect:
      - narrow buckets concentrated on round midpoints (50, 150, 250) if
        mechanism (b) is operative
      - wide buckets concentrated on century-slab midpoints (50.5, 150.5, ...)
        if mechanism (a) is operative
    """
    fig, axes = plt.subplots(len(WIDTH_BUCKETS), 1, figsize=(11, 14), sharex=True)
    bins = np.arange(ENVELOPE_MIN, ENVELOPE_MAX + 1, 1)
    for ax, (label, predicate) in zip(axes, WIDTH_BUCKETS):
        mask = predicate(df["width"].to_numpy())
        sub_mids = df.loc[mask, "midpoint"].to_numpy()
        ax.hist(sub_mids, bins=bins, color="#444477", edgecolor="none")
        ax.set_ylabel("count")
        ax.set_title(f"{label}  (n = {mask.sum():,})", loc="left", fontsize=10)
        # Reference lines at the spike years.
        for sy in SPIKE_YEARS:
            ax.axvline(sy, color="red", linestyle="--", lw=0.6, alpha=0.6)
        # Reference lines at the century-slab midpoints (e.g. 50.5 for [1,100]).
        for cm in [-49.5, 50.5, 150.5, 250.5]:
            ax.axvline(cm, color="orange", linestyle=":", lw=0.6, alpha=0.6)
    axes[-1].set_xlabel("Interval midpoint (year AD; negative = BC)")
    fig.suptitle(
        "Midpoint distribution stratified by interval width\n"
        "Red dashed = spike years AD 50/150/250; orange dotted = century-slab midpoints (e.g. 50.5 for [1,100])",
        fontsize=11,
    )
    fig.tight_layout(rect=[0, 0, 1, 0.97])
    fig.savefig(FIG_DIR / "fig2-midpoint-by-width.png", dpi=140)
    plt.close(fig)


# ---------------------------------------------------------------------------
# Q3 -- Spike decomposition by source-inscription width
# ---------------------------------------------------------------------------
def _aoristic_mass_in_bin(
    not_before: np.ndarray,
    not_after: np.ndarray,
    width: np.ndarray,
    bin_lo: int,
    bin_hi: int,
) -> np.ndarray:
    """Compute per-inscription aoristic mass deposited in [bin_lo, bin_hi].

    Inclusive integer years on both sides; overlap is
    max(0, min(not_after, bin_hi) - max(not_before, bin_lo) + 1).
    Uniform-aoristic mass per inscription is overlap / width.
    Returns a vector aligned with the input arrays.
    """
    overlap = np.maximum(
        0,
        np.minimum(not_after, bin_hi) - np.maximum(not_before, bin_lo) + 1,
    )
    return overlap / width


def _stacked_bar(
    pivot: pd.DataFrame,
    ylabel: str,
    title: str,
    out_path: Path,
    bucket_labels: list[str],
    spike_years: list[int],
) -> None:
    """Render a stacked bar plot for a spike-decomposition pivot table."""
    fig, ax = plt.subplots(figsize=(9, 6))
    bottom = np.zeros(len(spike_years))
    # Diverging palette -- cool blues for narrow buckets (mechanism b candidate),
    # warm reds for wide buckets (mechanism a candidate), grey for the 25 < w <= 50
    # middle bucket that doesn't cleanly attach to either mechanism.
    palette = ["#1b4f9c", "#3b6db8", "#6791d0", "#bdbdbd", "#e07b3a", "#c44a1a", "#7a2912"]
    for col, color in zip(bucket_labels, palette):
        vals = pivot[col].to_numpy()
        ax.bar(
            [f"AD {y}" for y in spike_years],
            vals,
            bottom=bottom,
            color=color,
            label=col,
            edgecolor="white",
            linewidth=0.5,
        )
        bottom = bottom + vals
    ax.set_ylabel(ylabel)
    ax.set_xlabel("Spike year")
    ax.set_title(title)
    ax.legend(loc="upper right", fontsize=8, title="Source width", title_fontsize=9)
    fig.tight_layout()
    fig.savefig(out_path, dpi=140)
    plt.close(fig)


def q3_spike_decomposition(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Two parallel decompositions of each spike, both stratified by source width.

    (a) 5-year-bin aoristic mass: contribution = overlap([nb,na],[Y-2,Y+2]) / width.
        Natural SPA-bin statistic; treats every contributing inscription
        proportionally to how much of its mass falls in the bin.
    (b) Integer-truncated midpoint count: contribution = 1 if int((nb+na)/2) == Y
        else 0. This reproduces the statistic used in
        runs/2026-04-23-descriptive-stats/code/profile.py::run_aoristic_mc_test
        (endpoint_label='mid'), which generated the headline 22.8x / 41.5x / 18.8x
        observed/expected ratios at AD 50 / 150 / 250.
    """
    nb = df["not_before"].to_numpy()
    na = df["not_after"].to_numpy()
    w = df["width"].to_numpy()
    # Integer-truncated midpoint, replicating profile.py line 670:
    #   mid = ((nb + na) / 2.0).astype(int)
    mid_int = ((nb + na) / 2.0).astype(int)

    rows_mass = []
    rows_count = []
    for spike in SPIKE_YEARS:
        bin_lo = spike - SPIKE_BIN_HALF_WIDTH
        bin_hi = spike + SPIKE_BIN_HALF_WIDTH
        mass = _aoristic_mass_in_bin(nb, na, w, bin_lo, bin_hi)
        # Integer-truncated midpoint match.
        mid_hit = (mid_int == spike).astype(float)
        total_mass = mass.sum()
        total_count = mid_hit.sum()
        for label, predicate in WIDTH_BUCKETS:
            bucket_mask = predicate(w)
            bucket_mass = mass[bucket_mask].sum()
            bucket_count = mid_hit[bucket_mask].sum()
            rows_mass.append({
                "spike_year": spike,
                "bin_lo": bin_lo,
                "bin_hi": bin_hi,
                "width_bucket": label,
                "n_contributing": int((mass[bucket_mask] > 0).sum()),
                "mass": float(bucket_mass),
                "total_mass": float(total_mass),
                "share_of_spike": float(bucket_mass / total_mass) if total_mass > 0 else 0.0,
            })
            rows_count.append({
                "spike_year": spike,
                "width_bucket": label,
                "n_contributing": int(bucket_count),
                "count": int(bucket_count),
                "total_count": int(total_count),
                "share_of_spike": float(bucket_count / total_count) if total_count > 0 else 0.0,
            })

    out_mass = pd.DataFrame(rows_mass)
    out_mass.to_csv(TBL_DIR / "spike-aoristic-mass-decomposition.csv", index=False)
    out_count = pd.DataFrame(rows_count)
    out_count.to_csv(TBL_DIR / "spike-midpoint-count-decomposition.csv", index=False)

    bucket_labels = [b[0] for b in WIDTH_BUCKETS]

    # Pivot (a): aoristic mass.
    pivot_mass = out_mass.pivot(index="spike_year", columns="width_bucket", values="mass")
    pivot_mass = pivot_mass.reindex(columns=bucket_labels).loc[SPIKE_YEARS]
    _stacked_bar(
        pivot_mass,
        ylabel="Aoristic mass in 5-year spike bin",
        title=(
            "(a) Aoristic-mass decomposition -- 5-year SPA bin\n"
            "Contribution = overlap with [Y-2, Y+2] / width"
        ),
        out_path=FIG_DIR / "fig3a-spike-aoristic-mass.png",
        bucket_labels=bucket_labels,
        spike_years=SPIKE_YEARS,
    )

    # Pivot (b): integer-truncated midpoint count (canonical -- matches headline ratios).
    pivot_count = out_count.pivot(index="spike_year", columns="width_bucket", values="count")
    pivot_count = pivot_count.reindex(columns=bucket_labels).loc[SPIKE_YEARS]
    _stacked_bar(
        pivot_count,
        ylabel="Inscriptions with int(midpoint) == spike year",
        title=(
            "(b) Integer-truncated-midpoint count -- the canonical statistic\n"
            "matches the 22.8x / 41.5x / 18.8x O/E ratios from the descriptive-stats run"
        ),
        out_path=FIG_DIR / "fig3b-spike-midpoint-count.png",
        bucket_labels=bucket_labels,
        spike_years=SPIKE_YEARS,
    )

    return out_mass, out_count


